# Reproduces Figure 8 (PAFA-DoH Performance Across Threat Vectors) from
# §4.25.1 of Chapter 4. The figure has three panels:
#
#   Panel (a) — DNS Tunneling Detection:      detection accuracy vs
#                                              training epochs, PAFA-DoH (SNN)
#                                              vs Quantum-DoH vs
#                                              Federated-DNSSEC vs AI-TDA.
#   Panel (b) — C2 Traffic Prevention:        same axes, C2 threat.
#   Panel (c) — Quantum SCA Resistance:       same axes, quantum side-
#                                              channel threat.
#
# Each curve is the mean accuracy across `n_seeds` training seeds,
# plotted with a 95 % confidence band. The curves are generated by
# simulating the PAFA-DoH training loop's convergence behaviour on the
# toy dataset; in full mode they would be generated from the actual
# training logs in `outputs/checkpoints/pafa_convergence_history.json`.
#
# Outputs:
#   outputs/figures/figure_8_threat_vectors.png
